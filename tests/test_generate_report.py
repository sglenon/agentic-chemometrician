class TestBuildAgentReadableSummary(unittest.TestCase):

    def test_returns_dict_with_all_required_keys(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        required_keys = {
            "run_id",
            "n_results",
            "failed_models",
            "n_warnings",
            "validation_passed",
            "best_accuracy",
            "models_run",
            "approval_required",
        }
        self.assertEqual(required_keys, set(summary.keys()))

    def test_approval_required_is_always_true(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        self.assertTrue(summary["approval_required"])

    def test_best_accuracy_is_highest_across_results(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        # SVM has accuracy 0.92, PCA has 0.85 — best should be 0.92
        self.assertAlmostEqual(summary["best_accuracy"], 0.92)

    def test_n_results_matches_result_count(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        self.assertEqual(summary["n_results"], 2)

    def test_best_accuracy_none_when_no_accuracy_metric(self):
        run = AnalysisRun(
            run_metadata=_make_run_metadata(),
            results=(
                AnalysisResult(
                    task_name="regression",
                    model_name="PLSRegression",
                    metrics={"rmse": 0.05, "r2": 0.98},
                ),
            ),
        )
        summary = build_agent_readable_summary(run)
        self.assertIsNone(summary["best_accuracy"])

    def test_validation_passed_reflects_summary(self):
        run = _make_analysis_run()
        vs = _make_validation_summary(passed=False)
        summary = build_agent_readable_summary(run, validation_summary=vs)
        self.assertFalse(summary["validation_passed"])

    def test_validation_passed_none_when_not_provided(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        self.assertIsNone(summary["validation_passed"])

    def test_run_id_from_metadata(self):
        run = _make_analysis_run(run_id="run-custom-id")
        summary = build_agent_readable_summary(run)
        self.assertEqual(summary["run_id"], "run-custom-id")

    def test_models_run_list(self):
        run = _make_analysis_run()
        summary = build_agent_readable_summary(run)
        self.assertIn("SVM", summary["models_run"])
        self.assertIn("PCA", summary["models_run"])



def _make_run_metadata(run_id: str = "run-test-abc123") -> RunMetadata:
    return RunMetadata(
        run_id=run_id,
        tool_name="run_analysis",
        dataset_id="test_dataset",
        status="completed",
        created_at="2026-01-01T00:00:00+00:00",
        parameters={"n_samples": 100, "n_features": 50},
    )


def _make_analysis_run(
    *,
    run_id: str = "run-test-abc123",
    include_failed: bool = False,
    include_warnings: bool = False,
    include_artifacts: bool = False,
    empty_results: bool = False,
) -> AnalysisRun:
    if empty_results:
        results: tuple = ()
    else:
        results = (
            AnalysisResult(
                task_name="classification",
                model_name="SVM",
                preprocessing=("snv", "savgol"),
                metrics={"accuracy": 0.92, "f1": 0.91},
            ),
            AnalysisResult(
                task_name="classification",
                model_name="PCA",
                preprocessing=("msc",),
                metrics={"accuracy": 0.85, "f1": 0.84},
            ),
        )

    failed_models = ("RandomForest",) if include_failed else ()
    warnings_list = (
        ValidationWarning(
            code="W001",
            message="Small sample size detected.",
            severity="warning",
        ),
    ) if include_warnings else ()
    artifacts = (
        ArtifactReference(
            kind="metrics_json",
            uri="runs/run-test-abc123/artifacts/metrics.json",
            label="Metrics",
        ),
    ) if include_artifacts else ()

    return AnalysisRun(
        run_metadata=_make_run_metadata(run_id),
        results=results,
        failed_models=failed_models,
        warnings=warnings_list,
        artifacts=artifacts,
    )


def _make_validation_summary(passed: bool = True) -> ValidationSummary:
    return ValidationSummary(
        passed=passed,
        checks={"no_leakage": True, "sufficient_samples": False},
        warnings=(
            ValidationWarning(
                code="V001",
                message="Insufficient samples for robust cross-validation.",
                severity="warning",
            ),
        ),
    )


def _make_interpretation_summary() -> InterpretationSummary:
    return InterpretationSummary(
        summary="SVM shows strong discriminative power in the 1000-1200 nm region.",
        important_features=(1100, 1150, 1200),
        model_comparisons=["SVM outperforms PCA on held-out test set."],
    )


